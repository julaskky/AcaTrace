<?php
declare(strict_types=1);

if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}

$userId = (int)($_SESSION["user_id"] ?? 0);
$role = strtolower((string)(
    $_SESSION["role"] ?? $_SESSION["user_type"] ?? ""
));

if ($userId <= 0 || $role !== "supervisor") {
    http_response_code(403);
    exit("Supervisor login required.");
}

require_once dirname(__DIR__, 2) . "/api/config/database.php";

$documentId = filter_input(INPUT_GET, "id", FILTER_VALIDATE_INT);
$mode = (string)($_GET["mode"] ?? "download");

if (!$documentId || $documentId <= 0 ||
    !in_array($mode, ["inline", "download"], true)) {
    http_response_code(400);
    exit("Invalid document request.");
}

try {
    // Confirm that this document belongs to a project assigned
    // to the currently logged-in supervisor.
    $stmt = $pdo->prepare("
        SELECT
            doc.id,
            doc.title,
            doc.original_filename,
            doc.stored_filename,
            doc.mime_type,
            doc.file_size
        FROM thesis_defense_documents doc
        INNER JOIN thesis_defenses td
            ON td.id = doc.defense_id
        INNER JOIN research_projects rp
            ON rp.id = td.research_project_id
        INNER JOIN supervisors sp
            ON sp.id = rp.supervisor_id
        WHERE doc.id = ?
          AND sp.user_id = ?
        LIMIT 1
    ");
    $stmt->execute([$documentId, $userId]);
    $document = $stmt->fetch(PDO::FETCH_ASSOC);

    if (!$document) {
        http_response_code(404);
        exit("Document not found or access denied.");
    }

    // Stored filenames are generated by the upload API.
    $storedFilename = (string)$document["stored_filename"];

    if (
        basename($storedFilename) !== $storedFilename ||
        !preg_match('/^[a-f0-9]{48}\.(pdf|doc|docx)$/i', $storedFilename)
    ) {
        http_response_code(400);
        exit("Invalid stored filename.");
    }

    $extension = strtolower(pathinfo($storedFilename, PATHINFO_EXTENSION));

    $allowedMimes = [
        "pdf"  => ["application/pdf"],
        "doc"  => ["application/msword", "application/octet-stream"],
        "docx" => [
            "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            "application/zip",
            "application/octet-stream"
        ]
    ];

    $mime = (string)$document["mime_type"];

    if (!in_array($mime, $allowedMimes[$extension], true)) {
        http_response_code(415);
        exit("Unsupported document type.");
    }

    // Matches the upload API: storage/thesis_defense.
    $storage = dirname(__DIR__, 2) . "/storage/thesis_defense";
    $filePath = $storage . "/" . $storedFilename;

    if (!is_file($filePath) || !is_readable($filePath)) {
        http_response_code(404);
        exit("The document file could not be found.");
    }

    // Only PDFs may be displayed inline. Word documents download.
    $inline = ($mode === "inline" && $extension === "pdf");
    $disposition = $inline ? "inline" : "attachment";

    $originalName = basename((string)$document["original_filename"]);
    $asciiName = preg_replace('/[^A-Za-z0-9._-]/', '_', $originalName);
    if (!$asciiName) {
        $asciiName = "thesis-defense-document." . $extension;
    }

    while (ob_get_level() > 0) {
        ob_end_clean();
    }

    header("Content-Type: " . $mime);
    header("Content-Length: " . (string)filesize($filePath));
    header(
        'Content-Disposition: ' . $disposition .
        '; filename="' . addcslashes($asciiName, '"\\') . '"' .
        "; filename*=UTF-8''" . rawurlencode($originalName)
    );
    header("X-Content-Type-Options: nosniff");
    header("Cache-Control: private, no-store, max-age=0");
    header("Pragma: no-cache");
    header("X-Frame-Options: SAMEORIGIN");

    readfile($filePath);
    exit;

} catch (Throwable $e) {
    error_log("Thesis defense document endpoint: " . $e->getMessage());
    http_response_code(500);
    exit("Unable to retrieve the document.");
}
